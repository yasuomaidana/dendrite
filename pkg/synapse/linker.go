// goWorkHeader marks a go.work written by Link; a go.work without it is hand-written and left alone.
const goWorkHeader = "// Code generated by dendrite synapse sync"

// LinkAction is what Link did with one workspace file.
type LinkAction string

const (
	LinkWritten   LinkAction = "written"
	LinkUnchanged LinkAction = "unchanged"
	LinkRemoved   LinkAction = "removed"
	LinkSkipped   LinkAction = "skipped"
)

// LinkResult reports the workspace file Link managed for one linking member.
type LinkResult struct {
	Alias    string     `json:"alias"`
	Strategy string     `json:"strategy"`
	File     string     `json:"file,omitempty"`
	Action   LinkAction `json:"action"`
	// Uses lists the members linked from their local checkout.
	Uses   []string `json:"uses,omitempty"`
	Reason string   `json:"reason,omitempty"`
}

// Link applies s.Sync.Strategy so that every consumer (and peer) builds against the
// local checkouts of the members whose source is local, and against its normal
// dependency resolution for members whose source is remote:
//
//   - go.work: writes <member>/go.work using the member itself plus every other local
//     Go member that is not a consumer. A go.work not written by Link is never touched;
//     a generated one with nothing left to link is removed.
//   - cargo-patch: maintains a delimited block in <member>/.cargo/config.toml with
//     [patch."<remote>"] <module> = { path = ... } for every other local Rust member
//     that has a remote URL and module (crate) name.
//
// Unresolved local members are skipped. Strategies "", "none" and "pnpm-workspace"
// produce no files.
func Link(s *Synapse) []LinkResult {
	switch s.Sync.Strategy {
	case "go.work":
		return linkMembers(s, "go.mod", linkGoWork)
	case "cargo-patch":
		return linkMembers(s, "Cargo.toml", linkCargoPatch)
	case "pnpm-workspace":
		return []LinkResult{{Strategy: s.Sync.Strategy, Action: LinkSkipped, Reason: "pnpm-workspace linking is not implemented"}}
	default:
		return nil
	}
}

// linkTarget is a local, resolved member carrying the strategy's manifest.
type linkTarget struct {
	m    Member
	path string
}

type linkFunc func(s *Synapse, self linkTarget, deps []linkTarget) LinkResult

func linkMembers(s *Synapse, manifest string, fn linkFunc) []LinkResult {
	var local []linkTarget
	var results []LinkResult
	for _, m := range s.Members {
		if m.IsRemote() {
			continue
		}
		path, err := Resolve(m)
		if err != nil {
			if m.Role != RoleProducer {
				results = append(results, LinkResult{Alias: m.Alias, Strategy: s.Sync.Strategy, Action: LinkSkipped, Reason: "local checkout does not resolve: " + err.Error()})
			}
			continue
		}
		if _, err := os.Stat(filepath.Join(path, manifest)); err != nil {
			continue
		}
		local = append(local, linkTarget{m: m, path: path})
	}
	for _, self := range local {
		if self.m.Role == RoleProducer {
			continue
		}
		var deps []linkTarget
		for _, d := range local {
			if d.m.ProjectID != self.m.ProjectID && d.m.Role != RoleConsumer {
				deps = append(deps, d)
			}
		}
		results = append(results, fn(s, self, deps))
	}
	return results
}

func linkGoWork(s *Synapse, self linkTarget, deps []linkTarget) LinkResult {
	res := LinkResult{Alias: self.m.Alias, Strategy: s.Sync.Strategy, File: filepath.Join(self.path, "go.work")}
	existing, err := os.ReadFile(res.File)
	generated := err == nil && bytes.HasPrefix(existing, []byte(goWorkHeader))
	if err == nil && !generated {
		res.Action, res.Reason = LinkSkipped, "hand-written go.work present"
		return res
	}
	if len(deps) == 0 {
		if !generated {
			res.Action, res.Reason = LinkUnchanged, "no local Go members to link"
			return res
		}
		if err := os.Remove(res.File); err != nil {
			res.Action, res.Reason = LinkSkipped, err.Error()
			return res
		}
		res.Action, res.Reason = LinkRemoved, "no local Go members left to link"
		return res
	}

	goVersion := goDirective(filepath.Join(self.path, "go.mod"))
	uses := []string{"."}
	for _, d := range deps {
		if v := goDirective(filepath.Join(d.path, "go.mod")); compareGoVersions(v, goVersion) > 0 {
			goVersion = v
		}
		uses = append(uses, relOrAbs(self.path, d.path))
		res.Uses = append(res.Uses, d.m.Alias)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s for synapse %q; DO NOT EDIT.\n", goWorkHeader, s.ID)
	b.WriteString("// Switch members with 'dendrite synapse set-source'; regenerate with 'dendrite synapse sync'.\n\n")
	if goVersion != "" {
		fmt.Fprintf(&b, "go %s\n\n", goVersion)
	}
	b.WriteString("use (\n")
	for _, u := range uses {
		fmt.Fprintf(&b, "\t%s\n", u)
	}
	b.WriteString(")\n")
	return writeIfChanged(res, existing, []byte(b.String()))
}

func linkCargoPatch(s *Synapse, self linkTarget, deps []linkTarget) LinkResult {
	res := LinkResult{Alias: self.m.Alias, Strategy: s.Sync.Strategy, File: filepath.Join(self.path, ".cargo", "config.toml")}
	byRemote := map[string][]string{}
	var skipped []string
	for _, d := range deps {
		if d.m.Remote == "" || d.m.Module == "" {
			skipped = append(skipped, d.m.Alias)
			continue
		}
		byRemote[d.m.Remote] = append(byRemote[d.m.Remote], fmt.Sprintf("%s = { path = %s }", d.m.Module, quoteString(d.path)))
		res.Uses = append(res.Uses, d.m.Alias)
	}
	if len(skipped) > 0 {
		res.Reason = "members without remote and module (crate) were not patched: " + strings.Join(skipped, ", ")
	}

	var block string
	if len(byRemote) > 0 {
		remotes := make([]string, 0, len(byRemote))
		for r := range byRemote {
			remotes = append(remotes, r)
		}
		sort.Strings(remotes)
		var b strings.Builder
		fmt.Fprintf(&b, "%s\n", blockStart(s.ID))
		b.WriteString("# Generated by 'dendrite synapse sync'; edits inside this block are overwritten.\n")
		for _, r := range remotes {
			fmt.Fprintf(&b, "[patch.%s]\n", quoteString(r))
			for _, line := range byRemote[r] {
				b.WriteString(line + "\n")
			}
		}
		fmt.Fprintf(&b, "%s\n", blockEnd(s.ID))
		block = b.String()
	}

	existing, err := os.ReadFile(res.File)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		res.Action, res.Reason = LinkSkipped, err.Error()
		return res
	}
	updated := replaceBlock(string(existing), s.ID, block)
	if strings.TrimSpace(updated) == "" {
		if err != nil {
			res.Action = LinkUnchanged
			return res
		}
		if rmErr := os.Remove(res.File); rmErr != nil {
			res.Action, res.Reason = LinkSkipped, rmErr.Error()
			return res
		}
		res.Action = LinkRemoved
		return res
	}
	return writeIfChanged(res, existing, []byte(updated))
}

func blockStart(id string) string { return "# >>> dendrite synapse " + id + " >>>" }
func blockEnd(id string) string   { return "# <<< dendrite synapse " + id + " <<<" }

// replaceBlock swaps the synapse's delimited block in content for block (removing it when
// block is empty), appending the block when content has none.
func replaceBlock(content, id, block string) string {
	start, end := blockStart(id), blockEnd(id)
	i := strings.Index(content, start)
	j := strings.Index(content, end)
	if i >= 0 && j > i {
		tail := content[j+len(end):]
		tail = strings.TrimPrefix(tail, "\n")
		return content[:i] + block + tail
	}
	if block == "" {
		return content
	}
	if content != "" && !strings.HasSuffix(content, "\n") {
		content += "\n"
	}
	if content != "" {
		content += "\n"
	}
	return content + block
}

func writeIfChanged(res LinkResult, existing, content []byte) LinkResult {
	if bytes.Equal(existing, content) {
		res.Action = LinkUnchanged
		return res
	}
	if err := os.MkdirAll(filepath.Dir(res.File), 0o755); err != nil {
		res.Action, res.Reason = LinkSkipped, err.Error()
		return res
	}
	if err := fsutil.WriteFileAtomic(res.File, content); err != nil {
		res.Action, res.Reason = LinkSkipped, err.Error()
		return res
	}
	res.Action = LinkWritten
	return res
}

// goDirective returns the version from the `go` line of a go.mod, or "".
func goDirective(goMod string) string {
	f, err := os.Open(goMod)
	if err != nil {
		return ""
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		if len(fields) == 2 && fields[0] == "go" {
			return fields[1]
		}
	}
	return ""
}

// compareGoVersions compares dotted Go versions numerically ("1.25" > "1.9"); "" sorts lowest.
func compareGoVersions(a, b string) int {
	pa, pb := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(pa) || i < len(pb); i++ {
		var x, y int
		if i < len(pa) {
			x, _ = strconv.Atoi(pa[i])
		}
		if i < len(pb) {
			y, _ = strconv.Atoi(pb[i])
		}
		if x != y {
			if x < y {
				return -1
			}
			return 1
		}
	}
	return 0
}

func relOrAbs(from, to string) string {
	if rel, err := filepath.Rel(from, to); err == nil {
		return filepath.ToSlash(rel)
	}
	return to
}
